-- Customer advance-credit ledger. Positive amounts add credit; negative amounts
-- apply credit to an order. Entries are append-only for auditability.
BEGIN;

CREATE TABLE IF NOT EXISTS public.customer_credit_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL DEFAULT public.app_current_tenant_id()
    REFERENCES public.tenants(id),
  customer_id INTEGER NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  order_id INTEGER REFERENCES public.orders(id) ON DELETE SET NULL,
  branch_id INTEGER REFERENCES public.branches(id) ON DELETE SET NULL,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('DEPOSIT', 'ORDER_OVERPAYMENT', 'APPLICATION', 'REVERSAL')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount <> 0),
  payment_method VARCHAR(50) NOT NULL,
  transaction_reference VARCHAR(255),
  payment_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes TEXT,
  created_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT customer_credit_entry_sign_check CHECK (
    (entry_type IN ('DEPOSIT', 'ORDER_OVERPAYMENT', 'REVERSAL') AND amount > 0)
    OR (entry_type = 'APPLICATION' AND amount < 0)
  )
);

CREATE INDEX IF NOT EXISTS idx_customer_credit_tenant_customer_date
  ON public.customer_credit_transactions (tenant_id, customer_id, payment_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_customer_credit_tenant_order
  ON public.customer_credit_transactions (tenant_id, order_id)
  WHERE order_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS public.customer_credit_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL DEFAULT public.app_current_tenant_id()
    REFERENCES public.tenants(id),
  application_transaction_id BIGINT NOT NULL
    REFERENCES public.customer_credit_transactions(id) ON DELETE RESTRICT,
  source_transaction_id BIGINT NOT NULL
    REFERENCES public.customer_credit_transactions(id) ON DELETE RESTRICT,
  allocation_type TEXT NOT NULL CHECK (allocation_type IN ('APPLY', 'RELEASE')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  created_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_customer_credit_alloc_source
  ON public.customer_credit_allocations (tenant_id, source_transaction_id, created_at, id);
CREATE INDEX IF NOT EXISTS idx_customer_credit_alloc_application
  ON public.customer_credit_allocations (tenant_id, application_transaction_id, created_at, id);
ALTER TABLE public.customer_credit_allocations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS customer_credit_alloc_tenant_isolation ON public.customer_credit_allocations;
CREATE POLICY customer_credit_alloc_tenant_isolation
  ON public.customer_credit_allocations FOR ALL
  USING (tenant_id = public.app_current_tenant_id())
  WITH CHECK (tenant_id = public.app_current_tenant_id());
CREATE UNIQUE INDEX IF NOT EXISTS idx_customer_credit_single_order_reversal
  ON public.customer_credit_transactions (tenant_id, order_id)
  WHERE entry_type = 'REVERSAL' AND order_id IS NOT NULL;

ALTER TABLE public.customer_credit_transactions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS customer_credit_tenant_isolation ON public.customer_credit_transactions;
CREATE POLICY customer_credit_tenant_isolation
  ON public.customer_credit_transactions
  FOR ALL
  USING (tenant_id = public.app_current_tenant_id())
  WITH CHECK (tenant_id = public.app_current_tenant_id());

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'soth_app') THEN
    GRANT SELECT, INSERT ON public.customer_credit_transactions TO soth_app;
    GRANT USAGE, SELECT ON SEQUENCE public.customer_credit_transactions_id_seq TO soth_app;
    GRANT SELECT, INSERT ON public.customer_credit_allocations TO soth_app;
    GRANT USAGE, SELECT ON SEQUENCE public.customer_credit_allocations_id_seq TO soth_app;
  END IF;
END $$;

COMMENT ON TABLE public.customer_credit_transactions IS
  'Append-only customer deposits, order overpayments, applications, and reversals. Positive entries add credit; negative applications consume it; reversals restore credit without representing new cash.';
COMMENT ON TABLE public.customer_credit_allocations IS
  'Maps each credit application to its source deposit. FIFO source allocation is the default; RELEASE entries restore source balances when an order is cancelled.';
COMMIT;
