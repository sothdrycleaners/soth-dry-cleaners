-- Optional, administrator-only PIN sign-in and super-admin reset workflow.
BEGIN;

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS admin_pin_hash TEXT,
  ADD COLUMN IF NOT EXISTS admin_pin_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS admin_pin_failed_attempts INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS admin_pin_locked_until TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.admin_pin_reset_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL DEFAULT public.app_current_tenant_id()
    REFERENCES public.tenants(id) ON DELETE RESTRICT,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'COMPLETED', 'DENIED')),
  resolved_at TIMESTAMPTZ,
  resolved_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  notes TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS admin_pin_reset_requests_one_pending_per_user
  ON public.admin_pin_reset_requests (tenant_id, user_id)
  WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS admin_pin_reset_requests_pending_order
  ON public.admin_pin_reset_requests (tenant_id, requested_at DESC)
  WHERE status = 'PENDING';

ALTER TABLE public.admin_pin_reset_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_pin_reset_requests FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS admin_pin_reset_requests_tenant_isolation_policy
  ON public.admin_pin_reset_requests;
CREATE POLICY admin_pin_reset_requests_tenant_isolation_policy
  ON public.admin_pin_reset_requests
  TO soth_app
  USING (tenant_id = public.app_current_tenant_id())
  WITH CHECK (tenant_id = public.app_current_tenant_id());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.admin_pin_reset_requests TO soth_app;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.admin_pin_reset_requests_id_seq TO soth_app;

COMMIT;
